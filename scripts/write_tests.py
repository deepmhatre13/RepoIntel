"""Helper to write the tree-sitter test file."""
import pathlib

lines = []
lines.append('"""Tests for the Tree-sitter multi-language parser and normalized model."""')
lines.append('')
lines.append('import pytest')
lines.append('')
lines.append('from packages.parsing.normalized_model import (')
lines.append('    NormalizedSymbol,')
lines.append('    NormalizedEdge,')
lines.append('    NormalizedFile,')
lines.append('    CLASS,')
lines.append('    FUNCTION,')
lines.append('    METHOD,')
lines.append('    IMPORT,')
lines.append('    CONTAINS,')
lines.append('    INHERITS,')
lines.append('    FROM_TREE_SITTER,')
lines.append('    FROM_PYTHON_AST,')
lines.append(')')
lines.append('from packages.parsing.tree_sitter_parser import (')
lines.append('    parse_file_with_tree_sitter,')
lines.append('    is_language_supported,')
lines.append('    supported_extensions,')
lines.append('    _get_language,')
lines.append(')')
lines.append('from packages.parsing.repository_parser import parse_file')


def w(s=''):
    lines.append(s)


w()
w('class TestNormalizedModel:')
w('    def test_symbol_creation(self):')
w('        sym = NormalizedSymbol(')
w('            repository_id="r1",')
w('            file_path="a.py",')
w('            language="Python",')
w('            symbol_name="MyClass",')
w('            symbol_type=CLASS,')
w('            line_start=1,')
w('            line_end=10,')
w('        )')
w('        assert sym.symbol_name == "MyClass"')
w('        assert sym.symbol_type == CLASS')
w('        assert sym.extraction_method == FROM_TREE_SITTER')
w('        assert sym.confidence == 1.0')
w()
w('    def test_edge_creation(self):')
w('        edge = NormalizedEdge(')
w('            repository_id="r1",')
w('            source_symbol="A",')
w('            source_file="a.py",')
w('            edge_type=INHERITS,')
w('            target_symbol="B",')
w('        )')
w('        assert edge.edge_type == INHERITS')
w('        assert edge.source_symbol == "A"')
w('        assert edge.target_symbol == "B"')
w()
w('    def test_file_creation(self):')
w('        f = NormalizedFile(')
w('            repository_id="r1",')
w('            file_path="a.py",')
w('            language="Python",')
w('        )')
w('        assert f.parse_succeeded is True')
w('        assert f.symbols == []')
w('        assert f.edges == []')
w()
w()
w('class TestLanguageSupport:')
w('    def test_supported_extensions(self):')
w('        exts = supported_extensions()')
w('        assert ".py" in exts')
w('        assert ".js" in exts')
w('        assert ".ts" in exts')
w()
w('    def test_is_language_supported_py(self):')
w('        assert is_language_supported(".py") is True')
w()
w('    def test_is_language_supported_js(self):')
w('        assert is_language_supported(".js") is True')
w()
w('    def test_is_language_supported_ts(self):')
w('        assert is_language_supported(".ts") is True')
w()
w('    def test_unsupported_extension(self):')
w('        assert is_language_supported(".xyz") is False')
w()
w('    def test_case_insensitive(self):')
w('        assert is_language_supported(".PY") is True')
w('        assert is_language_supported(".JS") is True')
w()
w()
w('class TestTreeSitterJavaScript:')
w('    def _parse(self, code, ext=".js"):')
w('        return parse_file_with_tree_sitter("r1", f"test{ext}", code, ext)')
w()
w('    def test_extracts_functions(self):')
w('        code = "function greet(name) { return name; }\\n"')
w('        result = self._parse(code)')
w('        assert result.parse_succeeded is True')
w('        names = [s.symbol_name for s in result.symbols]')
w('        assert "greet" in names')
w()
w('    def test_extracts_classes(self):')
w('        code = "class Animal { speak() { } }\\n"')
w('        result = self._parse(code)')
w('        types = {s.symbol_type for s in result.symbols}')
w('        assert CLASS in types')
w('        names = [s.symbol_name for s in result.symbols]')
w('        assert "Animal" in names')
w()
w('    def test_extracts_methods(self):')
w('        code = "class Dog { bark() { } }\\n"')
w('        result = self._parse(code)')
w('        method_syms = [s for s in result.symbols if s.symbol_type == METHOD]')
w('        assert len(method_syms) >= 1')
w('        assert result.methods >= 1')
w()
w('    def test_extracts_imports(self):')
w('        code = "import fs from \'fs\';\\n"')
w('        result = self._parse(code)')
w('        import_syms = [s for s in result.symbols if s.symbol_type == IMPORT]')
w('        assert len(import_syms) >= 1')
w()
w('    def test_produces_contains_edges(self):')
w('        code = "function foo() {}\\n"')
w('        result = self._parse(code)')
w('        contains_edges = [e for e in result.edges if e.edge_type == CONTAINS]')
w('        assert len(contains_edges) >= 1')
w()
w('    def test_preserves_line_numbers(self):')
w('        code = "\\n\\nfunction bar() {}\\n"')
w('        result = self._parse(code)')
w('        foo_sym = [s for s in result.symbols if s.symbol_name == "bar"]')
w('        assert len(foo_sym) == 1')
w('        assert foo_sym[0].line_start >= 2')
w()
w('    def test_preserves_evidence_excerpt(self):')
w('        code = "function example() { return 42; }\\n"')
w('        result = self._parse(code)')
w('        foo_sym = [s for s in result.symbols if s.symbol_name == "example"]')
w('        assert len(foo_sym) == 1')
w('        assert foo_sym[0].source_excerpt is not None')

pathlib.Path('scripts/write_tests.py').write_text('\n'.join(lines) + '\n', encoding='utf-8')
print(f"Part 1 written: {len(lines)} lines")
